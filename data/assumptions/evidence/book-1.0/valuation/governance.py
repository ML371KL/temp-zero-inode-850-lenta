def prev_day(s, d):
    ks = [k for k in s if k < d]
    return max(ks)


def on_or_before(s, d):
    return max(k for k in s if k <= d)


def idio_sd(s, end, n=250, beta=0.5):
    ks = sorted(k for k in s if k < end and k in mcftr)[-(n + 1):]
    ar = []
    for a, b in zip(ks, ks[1:]):
        ar.append((s[b] / s[a] - 1) - beta * (mcftr[b] / mcftr[a] - 1))
    m = sum(ar) / len(ar)
    return math.sqrt(sum((x - m) ** 2 for x in ar) / (len(ar) - 1))


def car(d0: dt.date, d1: dt.date, label: str, kind: str):
    """Доходность от закрытия дня перед d0 до закрытия d1 (включительно), бумага против MCFTR."""
    s = series_for(d0)
    a = prev_day(s, d0)
    b = on_or_before(s, d1)
    am, bm = on_or_before(mcftr, a), on_or_before(mcftr, b)
    ri, rm = s[b] / s[a] - 1, mcftr[bm] / mcftr[am] - 1
    ndays = len([k for k in s if a < k <= b])
    sd = idio_sd(s, d0) * math.sqrt(max(ndays, 1))
    return {"label": label, "kind": kind, "from": a.isoformat(), "to": b.isoformat(), "p0": s[a], "p1": s[b], "r": ri, "r_mcftr": rm,
            "ar_b1": ri - rm, "ar_b05": ri - 0.5 * rm, "days": ndays, "sd_window": sd, "t_b05": (ri - 0.5 * rm) / sd if sd else None}



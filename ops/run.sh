#!/usr/bin/env bash
#
# Один вход для всех тактов панели «Лента 850» (каркас — панель Магнита 850oa).
#
#     run.sh collect         утренний сбор: источники реестра, ротация архива,
#                            здоровье состояния; по понедельникам — тесты такта
#                            «в будущем» (FAKE_TODAY = сегодня + 60 дней)
#     run.sh daily           вечерний такт: сбор → нау-каст → тесты такта →
#                            сборка → публикация → сверка → прореживание
#     run.sh rebuild         раз в 15 минут: тихая проверка; если с опубликованного
#                            выпуска изменился код (CODE_DIRS) — тесты такта,
#                            сборка, публикация, сверка; дожимает сверку прошлого
#                            такта; БЕЗ сбора и нау-каста
#     run.sh rollback <sha>  вернуть на витрину прошлый выпуск (под тем же замком)
#
# КАНАЛ ДАННЫХ (DESIGN §2): сборка кладёт выпуск в $LENTA_STATE_DIR/release/,
# `ops/publish.py` коммитит его в ветку `release` (GitHub Pages этой ветки), а
# функция `functions/api/model.js` отдаёт его браузеру. Сверка читает выпуск
# через ту же боевую дверь, что и браузер.
#
# ГЛАВНОЕ ПРАВИЛО: упавший шаг означает, что на витрину НИЧЕГО не уходит.
# Вчерашний выпуск остаётся валидным, а витрина сама покажет возраст данных.
# Это лучше свежего мусора.
#
# КОДЫ ВОЗВРАТА — ЕДИНСТВЕННЫЙ КАНАЛ ТРЕВОГ. `ExecStopPost` каждого юнита зовёт
# общий мост /usr/local/sbin/dash-alert, а тот шлёт в Telegram СМЕНУ состояния
# по коду юнита:
#     0   — прошло, тревожить не о чем;
#     1   — ПРОВАЛ: упал шаг, выпуска нет (выше в журнале — «ПРОВАЛ на шаге «…»»);
#     8   — ТРЕВОГА: все шаги выполнены (выпуск, если такт его делает, на
#           витрине), но прогон требует внимания; последняя строка журнала
#           называет причину. Внутри такта это код 3 шагов (невосполнимый
#           источник, тревога сборки, сверка не дождалась выпуска, «будущее»
#           краснеет): причины копятся и уходят одним кодом в конце;
#     64  — неверный режим или проба тревоги с чужим источником;
#     75  — другой такт держит замок дольше LOCK_WAIT_SECONDS;
#     78  — нет env-файла или в нём нет обязательной переменной.
# Свой код тревоги (8, а не 1) нужен systemd: `RestartPreventExitStatus=8`
# у суточного такта снимает повтор тревоги (повтор её не снимет), а упавший
# шаг — например, моргнувший push в ветку release — повторяется через 3 минуты.
#
# Запускается из systemd под пользователем dash:
#     ExecStart=/bin/bash /srv/dash/repo-850-lenta/ops/run.sh daily
# Первый прогон на новой машине и откат — руками, чтобы видеть шаги:
#     sudo -u dash env ENV_FILE=/usr/local/etc/lenta-850/env bash ops/run.sh daily
set -Eeuo pipefail

# Абсолютный путь к САМОМУ СЕБЕ — до любого `cd`: после обновления кода такт
# перезапускается этим файлом (шаг «обновление кода»), а относительный `$0`
# после `cd "$REPO_DIR"` указывал бы не туда.
SELF="$(cd -- "$(dirname -- "$0")" && pwd -P)/$(basename -- "$0")"

# Метка перезапуска (её ставит шаг «обновление кода» перед `exec`) нужна
# только САМОМУ скрипту и снимается из окружения сразу. Иначе её унаследовали
# бы питон и тесты такта: песочницы `ops/run.sh` в pytest перезапущенного
# такта шли бы «как перезапущенные» — без своего `tee` и с чужой шапкой.
REEXEC_HEAD=${LENTA_REEXEC:-}
unset LENTA_REEXEC

MODE=${1:-daily}
case "$MODE" in
  collect|daily|rebuild) ;;
  rollback)
    ROLLBACK_SHA=${2:-}
    [[ $ROLLBACK_SHA =~ ^[0-9a-f]{12,64}$ ]] || {
      echo "откат: run.sh rollback <хэш выпуска, от 12 шестнадцатеричных знаков>" >&2; exit 64; }
    ;;
  *) echo "режим: collect|daily|rebuild|rollback <sha>" >&2; exit 64;;
esac

ENV_FILE=${ENV_FILE:-/usr/local/etc/lenta-850/env}
[[ -r $ENV_FILE ]] || { echo "нет доступа к $ENV_FILE" >&2; exit 78; }
set -a; . "$ENV_FILE"; set +a

# Оба каталога обязательны. Запасной /tmp для состояния под PrivateTmp=yes дал
# бы КАЖДОМУ запуску свой приватный каталог, и замок перестал бы защищать что-
# либо; каталог кода «по месту скрипта» в песочнице тестов сбросил бы
# `git reset --hard` рабочее дерево разработчика.
[[ -n ${LENTA_REPO_DIR:-} ]] || { echo "в $ENV_FILE не задан LENTA_REPO_DIR" >&2; exit 78; }
[[ -n ${LENTA_STATE_DIR:-} ]] || { echo "в $ENV_FILE не задан LENTA_STATE_DIR" >&2; exit 78; }
REPO_DIR=$LENTA_REPO_DIR
STATE_DIR=$LENTA_STATE_DIR
VENV=${LENTA_VENV:-$REPO_DIR/.venv}
PY=${LENTA_PYTHON:-$VENV/bin/python}
# Отметка установленных зависимостей живёт В САМОМ venv: пересозданное
# окружение теряет её вместе с пакетами, и такт поставит их заново.
REQ_MARK="$VENV/.requirements.sha256"
cd "$REPO_DIR"
mkdir -p "$STATE_DIR/logs"

# Русские логи под systemd уезжают в journald как есть. Но тот же скрипт руками
# из окружения с однобайтовой локалью роняет питон на UnicodeEncodeError.
export PYTHONIOENCODING=utf-8
export LENTA_STATE_DIR="$STATE_DIR"

# Сколько плановый такт ждёт замок, занятый другим тактом. Пересборка идёт в
# любой момент и держит замок на тесты, сборку и сверку: сбор, который упёрся
# бы в неё с кодом 75, за три перезапуска юнита по 3 минуты мог и не
# дождаться — и невосполнимый день источника был бы потерян. Поэтому плановый
# такт ждёт столько же, сколько пересборка может держать замок: её потолок
# RuntimeMaxSec (ops/systemd/lenta850-rebuild.service, расчёт — ops/budgets.json;
# равенство сверяет тест).
LOCK_WAIT_SECONDS=${LOCK_WAIT_SECONDS:-2640}

# Каталоги кода, который считает число: их правка с опубликованного выпуска
# будит пересборку. Ровно `CODE_DIRS` выпуска (model/payload.py) в том же
# порядке, включая requirements.txt: новая версия зависимости — это новый код
# (сверяет тест `test_run_sh_code_dirs_are_the_release_code_dirs`).
# Файлы `*.md` внутри (ops/README.md) — документы и пересборку не будят.
CODE_DIRS=(model indicators ops data/assumptions data/facts requirements.txt)
# Отметки (пишет `ops/publish.py`, ops/README.md «Что где»):
#   release.commit — код выпуска, ПОДТВЕРЖДЁННОГО сверкой через боевую дверь;
#   release.pushed — выпуск в ветке, сверка ещё не прошла (её дожимает пересборка);
#   rebuild.tried  — коммит, на котором пересборка уже запускалась (пишет run.sh):
#                    упавшая пересборка не повторяется каждые 15 минут;
#   future.checked — «день код» прогона «в будущем» (пишет run.sh): повтор
#                    утреннего юнита его не гоняет заново.
BUILT_MARK="$STATE_DIR/release.commit"
PUSHED_MARK="$STATE_DIR/release.pushed"
TRIED_MARK="$STATE_DIR/rebuild.tried"
# Тесты такта — БЕЛЫЙ СПИСОК: только тесты с меткой `tact` (pytest.ini). Новый
# тест без метки в такт не попадает, и такт не распухает сам собой (у 850oa он
# вырос с 7 до 22 минут). `not ci_only` — страховка: противоречивая пара меток
# не тащит в такт полный выпуск, и сторож tests/conftest.py видит прогон такта.
TACT_TESTS="tact and not network and not docs and not ci_only"
# Прогон «в будущем» в утреннем такте: день недели (1 — понедельник, `date +%u`)
# и сдвиг даты. Дублирует ежемесячный прогон CI, потому что GitHub выключает
# расписание публичного репозитория после 60 дней без активности.
FUTURE_WEEKDAY=${LENTA_FUTURE_WEEKDAY:-1}
FUTURE_DAYS=${LENTA_FUTURE_DAYS:-60}
FUTURE_MARK="$STATE_DIR/future.checked"
# Наборы сборщиков `indicators.collect` для утреннего и вечернего такта.
# Вечерний повторяет невосполнимые источники (`--retry`): отчёты Ленты
# выходят в 10:00 МСК, и раскрытие вечером ловит их в тот же день.
COLLECT_MORNING=daily
COLLECT_EVENING=daily

LOCKED=""
if [[ $MODE == rebuild && -z $REEXEC_HEAD ]]; then
  # ── Тихая проверка пересборки ─────────────────────────────────────────────
  # Почти всегда делать нечего, и проверка обязана быть тихой: без шапки, без
  # строк в журнале файла и без обращения к источникам.
  if command -v flock >/dev/null 2>&1; then
    exec 9>"$STATE_DIR/run.lock"
    # Идёт другой такт: код он подхватит сам или его увидит следующая проверка.
    flock -n 9 || exit 0
    LOCKED=1
  fi
  pending_code=""
  if [[ -s $PUSHED_MARK ]]; then
    # Прошлый такт отправил выпуск в ветку release, но сверка его не дождалась
    # (сборка GitHub Pages встала в очередь). Одна попытка — один GET: прошла —
    # publish.py сам пишет release.commit; нет — код выпуска запоминается, чтобы
    # не пересобирать и не пушить тот же код каждые 15 минут.
    if ! "$PY" ops/publish.py --verify --once; then
      pending_code=$(sed -n 's/^ *"code_commit": *"\([0-9a-f]*\)".*/\1/p' "$PUSHED_MARK" 2>/dev/null || true)
    fi
  fi
  if ! git fetch --quiet origin main 2>/dev/null; then
    # Моргнувший GitHub — не повод для тревоги: через 15 минут спросим снова,
    # а суточный такт упал бы на публикации и сообщил бы сам.
    echo "пересборка: main на GitHub сейчас не читается — проверю через 15 минут" >&2
    exit 0
  fi
  target=$(git rev-parse origin/main)
  built=$(cat "$BUILT_MARK" 2>/dev/null || true)
  if [[ -n $built ]] && git diff --quiet "$built" "$target" -- "${CODE_DIRS[@]}" ':(exclude)*.md' 2>/dev/null; then
    exit 0
  fi
  if [[ -n $pending_code && $pending_code == "$target" ]]; then
    # Выпуск на этом коде уже в ветке и ждёт GitHub Pages; тревогу «не
    # подтверждено» прислал такт, который его отправил.
    echo "пересборка: выпуск на коммите ${target:0:8} уже в ветке release и ждёт сверки — не пересобираю" >&2
    exit 0
  fi
  if [[ $(cat "$TRIED_MARK" 2>/dev/null || true) == "$target" ]]; then
    # Код 1 без работы: мост тревог шлёт смену состояния, поэтому «упало»
    # уже пришло один раз и не повторяется, а «снова проходит» придёт, когда
    # выпуск на этом коде соберёт суточный такт или пересборку пройдёт новый коммит.
    echo "ПРОВАЛ (код 1): пересборка на коммите ${target:0:8} уже запускалась и не довела выпуск до витрины (журнал: journalctl -u lenta850-rebuild) — повтор будет с новым коммитом в main, на этом коде выпуск соберёт суточный такт" >&2
    exit 1
  fi
  echo "$target" > "$TRIED_MARK"
fi

# Лог в файл плюс journald. Нужны оба: journald ротируется по общему объёму
# машины, а разбирать инцидент недельной давности приходится по файлу.
# Перезапущенный после обновления кода такт (REEXEC_HEAD) уже пишет в тот же
# `tee`: второй `tee` поверх первого удвоил бы каждую строку файла.
LOG_FILE="$STATE_DIR/logs/$(date -u +%F).log"
if [[ -z $REEXEC_HEAD ]]; then
  exec > >(tee -a "$LOG_FILE") 2>&1
fi
find "$STATE_DIR/logs" -name '*.log' -mtime +45 -delete 2>/dev/null || true

STEP="старт"
step() { STEP="$*"; echo; echo "── $* ── $(date -u +%T)Z"; }
# Упавший шаг — всегда код 1, каким бы ни был код самой команды (он есть в
# строке журнала): иначе, например, 8 от случайной команды мост принял бы за
# тревогу при опубликованном выпуске.
fail() { echo "ПРОВАЛ на шаге «$STEP» (код $1). На витрине остаётся прежний выпуск." >&2; exit 1; }
trap 'fail $?' ERR

# Накопитель причин тревоги. Пустая строка означает «код 0»: тревога без
# названной причины бесполезна, поэтому текст и код всегда идут вместе.
ALARM=""
alarm_add() { ALARM="${ALARM:+$ALARM; }$1"; }

finish() {
  echo
  echo "готово: $(date -u +%FT%TZ)"
  if [[ -n $ALARM ]]; then
    echo "ТРЕВОГА (код 8): $ALARM" >&2
    exit 8
  fi
  exit 0
}

# Проба доставки тревоги: источник объявляется отказавшим БЕЗ обращения к нему.
# Нужна на сервере — иначе «мост шлёт» проверялось бы только рассуждением.
SIMULATE=()
if [[ -n ${LENTA_SIMULATE_FAILURE:-} ]]; then
  echo "ПРОБА ТРЕВОГИ: источник $LENTA_SIMULATE_FAILURE будет объявлен отказавшим" >&2
  SIMULATE=(--simulate-failure "$LENTA_SIMULATE_FAILURE")
fi

# Один вход к сборщикам для обоих тактов сбора. Код 3 — «работа закончена, но
# отказал невосполнимый источник» (`indicators.collect.ALARM_EXIT`): такт
# обязан идти дальше и довести выпуск до витрины, а тревога уйдёт кодом 8 в
# самом конце. 64 — проба тревоги с источником не из этого такта: «проба
# прошла, тревоги нет» было бы тем самым тихим нулём. Прочее — падение шага.
run_collect() {
  local rc=0
  "$PY" -m indicators.collect "$@" "${SIMULATE[@]}" || rc=$?
  case $rc in
    0) ;;
    3) alarm_add "невосполнимый источник не собран (строки «ОШИБКА:» выше) — пропущенный день не добирается никогда" ;;
    64) echo "проба тревоги: источник не из этого такта (строка выше)" >&2; exit 64 ;;
    *) fail "$rc" ;;
  esac
}

# Тесты такта. Ноль выбранных тестов (pytest: код 5) — провал, а не успех:
# белый список, который никого не пускает, выключил бы проверку перед выпуском.
run_tact_tests() {
  local rc=0
  "$PY" -m pytest -q -m "$TACT_TESTS" || rc=$?
  case $rc in
    0) ;;
    5) echo "ни одного теста с меткой tact: проверять нечего, выпуск без проверок не выходит" >&2; fail 5 ;;
    *) fail "$rc" ;;
  esac
}

# Выпуск: сборка, публикация, сверка и прореживание. Общий хвост суточного
# такта и пересборки — у выпуска один путь на витрину.
build_and_publish() {
  step "сборка выпуска"
  # build_release возвращает ненулевой код при нарушенном инварианте,
  # сломанном контракте или необъяснённом гейте — такт останавливается, на
  # витрине остаётся прежний выпуск. Код 3 — выпуск собран и записан, но масса
  # гейта разошлась с ожидаемой из объяснения или срок объяснения на исходе
  # (меньше 30 дней): публиковать можно, тревога уйдёт в конце такта.
  local rc=0
  "$PY" ops/build_release.py || rc=$?
  case $rc in
    0) ;;
    3) alarm_add "сборка подняла тревогу (строки «ТРЕВОГА:» выше): масса гейта разошлась с ожидаемой или срок объяснения гейта истекает — выпуск опубликован" ;;
    *) fail "$rc" ;;
  esac

  step "публикация в ветку release"
  # Сначала неизменяемый releases/<sha256>.json, потом указатель — в одном
  # коммите; push с повтором. Отказ — код 1: у суточного такта systemd
  # повторит его через 3 минуты.
  "$PY" ops/publish.py

  step "сверка через боевую дверь"
  # Читаем ЧЕРЕЗ ТУ ЖЕ дверь, что и браузер, до совпадения хэша и
  # published_at. Код 3 — выпуск в ветке, но GitHub Pages его не отдал за
  # отведённое время (или витрина живёт на запасном источнике): это тревога, а
  # не провал — выпуск уже ушёл, сверку дожмёт пересборка, release.commit
  # появится только после неё.
  rc=0
  "$PY" ops/publish.py --verify || rc=$?
  case $rc in
    0) ;;
    3) alarm_add "выпуск отправлен в ветку release, но боевая дверь не подтвердила его (строки «СВЕРКА:» выше) — сверку дожмёт пересборка; прореживание отложено"
       return 0 ;;
    *) fail "$rc" ;;
  esac

  step "прореживание старых выпусков"
  # Только после подтверждённой сверки. Отказ прореживания выпуск не отменяет:
  # тревога, а не провал.
  rc=0
  "$PY" ops/publish.py --prune || rc=$?
  [[ $rc == 0 ]] || alarm_add "прореживание ветки release не прошло (код $rc, строки выше) — выпуск на витрине, лишние файлы уберёт следующий такт"
}

echo "=============================================================="
echo "Лента 850 · такт $MODE · $(date -u +%FT%TZ) · $REPO_DIR"
if [[ -n $REEXEC_HEAD ]]; then
  echo "(перезапуск тем же тактом: код обновлён до ${REEXEC_HEAD:0:8}, исполняется новый ops/run.sh)"
fi
echo "=============================================================="

# Замок один на все такты и на откат: сбор и суточный прогон пишут в одну базу
# винтажей, публикация и откат — в один клон ветки release. Перезапущенный
# такт наследует дескриптор 9 от самого себя до `exec` — вместе с уже взятым
# замком; пересборка взяла его ещё на тихой проверке. Открыть файл заново
# значило бы отпустить замок и взять его снова: между этими двумя мгновениями
# его мог бы перехватить другой такт.
if [[ -n $REEXEC_HEAD || -n $LOCKED ]] && { : >&9; } 2>/dev/null; then
  :
else
  exec 9>"$STATE_DIR/run.lock"
fi
if command -v flock >/dev/null 2>&1; then
  if ! flock -n 9; then
    echo "  замок у другого такта (например, у пересборки) — жду до ${LOCK_WAIT_SECONDS} с"
    # Код 75 (EX_TEMPFAIL), а не 0: при нулевом мост отрапортовал бы
    # «снова проходит», хотя не выполнилось ничего. Юнит перезапустится сам.
    flock -w "$LOCK_WAIT_SECONDS" 9 || { echo "прогон уже идёт, выхожу" >&2; exit 75; }
  fi
else
  echo "  ВНИМАНИЕ: flock не найден — прогон БЕЗ защиты от параллельного запуска"
fi

if [[ $MODE == rollback ]]; then
  # Откат — пауза на один такт, а не состояние: ближайший суточный такт (или
  # пересборка на новом коммите) соберёт новый выпуск и перепишет указатель.
  # Если причина не устранена — остановить таймеры (ops/README.md, «Откат»).
  # Кода откат не обновляет: он должен быть быстрым и делать ровно одно.
  step "откат указателя latest.json на ${ROLLBACK_SHA:0:12}"
  "$PY" ops/publish.py rollback "$ROLLBACK_SHA"
  step "сверка через боевую дверь"
  rc=0
  "$PY" ops/publish.py --verify || rc=$?
  case $rc in
    0) ;;
    3) alarm_add "откат отправлен в ветку release, но боевая дверь его не подтвердила (строки «СВЕРКА:» выше)" ;;
    *) fail "$rc" ;;
  esac
  finish
fi

step "обновление кода"
if ! git fetch --quiet origin main; then
  # Моргнувший GitHub не должен стоить невосполнимого дня сбора: такт идёт на
  # текущем коде, новый подхватит следующий. Публикация (тот же GitHub)
  # откажет сама и назовёт себя.
  echo "  ВНИМАНИЕ: main на GitHub не читается — такт идёт на текущем коде $(git rev-parse --short HEAD)" >&2
else
  local_head=$(git rev-parse HEAD)
  remote_head=$(git rev-parse origin/main)
  if [[ $local_head == "$remote_head" ]]; then
    echo "  HEAD не менялся: ${local_head:0:8}"
  else
    echo "  код обновился ${local_head:0:8} -> ${remote_head:0:8}; сбрасываю дерево"
    # Безопасно: данные и выходы в git не коммитятся (var/ в .gitignore,
    # состояние — в $LENTA_STATE_DIR), сбрасывается только код и входы книги.
    git reset --hard --quiet origin/main
    # ПЕРЕЗАПУСК НОВЫМ run.sh. bash читает скрипт по ходу исполнения из уже
    # открытого файла, а `git reset --hard` кладёт на диск НОВЫЙ файл: этот
    # такт до конца исполнял бы ПРЕЖНИЙ run.sh — со старым порядком шагов и
    # старыми тревогами (у 850oa подтверждено журналом такта 23.09.2026).
    # `exec` заменяет процесс тем же PID — systemd видит тот же юнит, замок и
    # журнал наследуются, — и новый файл проходит такт с начала.
    #
    # Защита от петли — переменная окружения LENTA_REEXEC: перезапуск один на
    # такт. Если за время такта код обновился ЕЩЁ раз, второй перезапуск не
    # делается — новый run.sh вступит в силу со следующего такта.
    if [[ -z $REEXEC_HEAD ]]; then
      echo "  перезапускаю такт новым ops/run.sh"
      export LENTA_REEXEC="$remote_head"
      exec "$BASH" "$SELF" "$@"
    fi
    echo "  ВНИМАНИЕ: код обновился повторно за один такт (${REEXEC_HEAD:0:8} -> ${remote_head:0:8}); перезапуск уже был — новый ops/run.sh вступит в силу со следующего такта"
  fi
fi
echo "  HEAD: $(git rev-parse --short HEAD)"

step "зависимости"
# По отметке sha256(requirements.txt) — КАЖДЫЙ такт, а не только при смене
# HEAD. У 850oa pip шёл сразу после `reset --hard`: упади он (PyPI недоступен),
# следующий такт видел HEAD равным origin и pip больше не звал — новый код
# работал на старых пакетах до следующей правки. Здесь отметка пишется только
# после удачной установки, а неудача — провал такта (код 1): считать число
# новым кодом на старых пакетах нельзя.
req_sha=$(sha256sum requirements.txt | cut -d' ' -f1)
req_had=$(cat "$REQ_MARK" 2>/dev/null || true)
if [[ $req_had == "$req_sha" ]]; then
  echo "  на месте: requirements.txt ${req_sha:0:12}"
else
  echo "  requirements.txt ${req_had:0:12}${req_had:+ -> }${req_sha:0:12}: ставлю"
  "$PY" -m pip install --quiet --disable-pip-version-check -r requirements.txt
  echo "$req_sha" > "$REQ_MARK"
fi

if [[ $MODE == rebuild ]]; then
  # Входы — те, что собрал последний такт: цена, кривая, ряды, журнал
  # прогнозов. Меняется только код. Тесты — те же, что у суточного такта, и до
  # сборки: пересборка появилась ради правок кода, а не в обход проверок.
  step "тесты такта"
  run_tact_tests
  build_and_publish
  finish
fi

step "сбор источников"
if [[ $MODE == daily ]]; then
  run_collect "$COLLECT_EVENING" --retry
else
  run_collect "$COLLECT_MORNING"
fi

if [[ $MODE == collect ]]; then
  if [[ $(date -u +%u) == "$FUTURE_WEEKDAY" ]]; then
    step "тесты такта «в будущем» (+$FUTURE_DAYS дней)"
    # Тест или срок объяснения гейта, завязанный на дату, остановит суточный
    # такт в тот день, когда наступит. Здесь это видно за FUTURE_DAYS дней —
    # тревогой, а не блокировкой: сегодня выпускать ничто не мешает.
    # Итог дня помнится в future.checked: повтор юнита через 3 минуты (он
    # добирает моргнувший источник) не гоняет тесты заново, а повторяет итог.
    today=$(date -u +%F)
    future=$(date -u -d "+$FUTURE_DAYS days" +%F)
    read -r checked_day checked_rc < "$FUTURE_MARK" 2>/dev/null || true
    if [[ ${checked_day:-} == "$today" && ${checked_rc:-} =~ ^[0-9]+$ ]]; then
      rc=$checked_rc
      echo "  уже проверено сегодня (код $rc) — повтор юнита тесты заново не гоняет"
    else
      rc=0
      FAKE_TODAY=$future "$PY" -m pytest -q -m "$TACT_TESTS" || rc=$?
      echo "$today $rc" > "$FUTURE_MARK"
    fi
    [[ $rc == 0 ]] || alarm_add "тесты такта с FAKE_TODAY=$future падают (код $rc, строки выше): через $FUTURE_DAYS дней суточный такт остановится — продлить объяснение гейта или поправить тест"
  fi

  step "прореживание сырого архива"
  # Источники без истории защищены списком в indicators/store.py
  # (`PROTECTED_SOURCES`) и здесь не трогаются ни при каких обстоятельствах.
  "$PY" -c "from indicators.store import Store; removed = Store().prune_raw(); print('  прорежено дней:', len(removed)); [print('   ', r) for r in removed[:10]]"

  step "объём состояния"
  "$PY" -m indicators.collect status

  step "здоровье состояния"
  # ТРЕВОГА, А НЕ БЛОКИРОВКА — и здесь, в отличие от суточного такта, она
  # обязана дойти кодом: утренний такт единственный, кто спрашивает о
  # здоровье состояния каждый день.
  if ! "$PY" -m indicators.collect health; then
    alarm_add "состояние не в порядке (строки «НЕ В ПОРЯДКЕ» выше)"
  fi

  finish
fi

step "нау-каст ближайшего отчёта"
# Прогноз фиксируется в журнале ДО выхода факта — иначе сравнивать будет не с
# чем. Код 3 — «дисциплина журнала нарушена: факт вышел, а его не внесли».
# Выпуск от нау-каста НЕ ЗАВИСИТ (к цене он не подключён), поэтому такт идёт
# дальше, а тревога уходит в самом конце.
rc=0
"$PY" -m indicators.collect nowcast || rc=$?
case $rc in
  0) ;;
  3) alarm_add "нау-каст не записан: дисциплина журнала (строка «ЖУРНАЛ:» выше) — нужен ручной \`collect record-actual\`" ;;
  *) fail "$rc" ;;
esac

step "здоровье состояния"
# Напоминание, а не тревога: о нездоровом состоянии владелец уже узнал кодом
# утреннего такта, который спрашивает то же самое. Дублировать тревогу —
# значит слать одну новость дважды в день.
if ! "$PY" -m indicators.collect health; then
  echo "  ВНИМАНИЕ: состояние не в порядке (см. строки выше). Выпуск продолжается." >&2
  STATE_UNHEALTHY=1
fi

step "тесты такта"
# ДО сборки: выпуск с нарушенными инвариантами не должен уйти на витрину.
run_tact_tests

build_and_publish

step "объём состояния"
"$PY" -m indicators.collect status
[[ ${STATE_UNHEALTHY:-0} == 0 ]] || echo "напоминание: состояние требует внимания" >&2

finish

"""Отображение V0 → капитал акционера: внутренняя стоимость (DESIGN D4).

Капитал = max(V0 − D, 0), до дисконта за управление; печатаемая оценка —
max(V0 − D, 0)·(1 − g)·1000 / акции в обращении (`valuation.headline.method:
intrinsic`). Основание: у Ленты рычаг ≈1,4× EBITDA и V*/D ≈ 2,9 — опционная
часть ограниченной ответственности меньше 0,2 % цены даже на P10, а σ активов
по спредам не определяется. Структурное отображение 850oa (колл Мертона,
страйк K′, калибровка σ, затухание надбавки, σ на живой цене, кредитный пут)
в этом репозитории не держится: оно нужно было только для приёмки переноса
ядра на книге Магнита и осталось в песочнице переноса. Там, где V0 близко к D
и ограниченная ответственность перестаёт быть мелочью, об этом говорит
совещательный гейт `limited_liability` (`model.checks`): метод меняет только
новая версия книги.

Отображение — кортеж `layer_mapping`: ЕДИНСТВЕННАЯ точка, где выбирается
метод; все потребители (слой, V*, EV центра и медианы, аналоги, клетка) берут
его отсюда, а капитал — из `mapped_equity`. Кортеж, а не число D, — чтобы смена
метода книгой была правкой одного места.

Единицы: V0, D — млрд ₽.
"""

from __future__ import annotations

INTRINSIC = "intrinsic"


def layer_mapping(A: dict, claims: float) -> tuple:
    """Параметры отображения V0 → капитал при требованиях `claims`: ("intrinsic", D).

    Метод — `valuation.headline.method` (проверяет `model.book.headline_block`);
    другого метода ядро не знает.
    """
    from model.book import headline_method

    headline_method(A)
    return (INTRINSIC, claims)


def mapped_equity(mapping: tuple, v0: float) -> float:
    """Капитал акционера до дисконта за управление, млрд ₽: max(V0 − D, 0)."""
    return max(v0 - mapping[1], 0.0)


def mapping_scale(mapping: tuple) -> float:
    """Масштаб требований отображения (D) — верх отрезка поиска V*
    (`model.grid.solve_v0`)."""
    return mapping[1]
